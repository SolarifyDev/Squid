using Squid.Core.Services.OctopusImport.Mapping.Actions;
using Squid.Core.Services.OctopusImport.Octopus;
using Squid.Message.Enums.OctopusImport;
using Squid.Message.Models.OctopusImport;

namespace Squid.Core.Services.OctopusImport.Mapping.Scripts;

/// <summary>
/// Makes an imported Octopus inline script run unchanged on Squid by prepending a small, clearly
/// delimited compatibility preamble:
/// <list type="bullet">
///   <item>Step-template parameter values (from the action, else the template default) become
///         <c>$OctopusParameters['Name']</c> entries and — for valid, non-reserved identifiers — <c>$Name</c>
///         PowerShell variables, matching what Octopus/Calamari exposes. Parameters referencing each other
///         (<c>#{BaseUrl}/send</c>) are resolved at import time, in values and in the script body.</item>
///   <item>Every key the script reads through <c>$OctopusParameters['…']</c> (PowerShell) or
///         <c>get_octopusvariable "…"</c> (Bash) is defined: Octopus built-ins map to their Squid
///         equivalent, other names resolve to the Squid variable of the same name.</item>
/// </list>
/// Values never become script text: import-time text is base64-encoded, and every deploy-time value is
/// emitted as <c>'#{Name | ToBase64}'</c>, so Squid's substitution can only ever produce base64 characters
/// inside single quotes. A small decoder in the preamble turns the pieces back into the value; a piece
/// Squid could not resolve (still <c>#{…}</c>) decodes to empty, which is what Octopus returns for an
/// undefined variable.
/// </summary>
internal static partial class OctopusScriptCompatibility
{
    public const string PreambleStartMarker = "# --- Squid: Octopus compatibility (generated by Octopus import) ---";
    public const string PreambleEndMarker = "# --- end Octopus compatibility ---";

    public static OctopusScriptCompatibilityResult Apply(OctopusDeploymentActionDto action, string syntax, string scriptBody, OctopusActionTemplateDto template)
    {
        var ctx = new CompatibilityContext(action, syntax, scriptBody ?? string.Empty, template);

        ResolveTemplateParameters(ctx);
        WarnUnsupportedVariableAccess(ctx);
        WarnUnparsableSubstitution(ctx);
        ExtractReferencedKeys(ctx);
        SubstituteParameterReferencesInBody(ctx);

        if (ctx.Parameters.Count == 0 && ctx.References.Count == 0) return ctx.Result(ctx.Body);

        BuildEntries(ctx);

        var preamble = RenderPreamble(ctx);

        if (preamble == null) return ctx.Result(ctx.Body);

        ctx.Report(OctopusImportCompatibilitySeverity.Info, OctopusImportActionMappingDiagnosticCodes.ScriptOctopusCompatibilityAdded, $"Octopus script action '{action.Name}' received a compatibility preamble defining {ctx.Entries.Count} Octopus parameter(s) for Squid.");

        return ctx.Result(preamble + WithoutLeadingByteOrderMark(ctx.Body));
    }

    // A BOM is only meaningful as the first bytes of a file; behind the preamble it is a stray character
    // PowerShell and bash both fail on.
    private static string WithoutLeadingByteOrderMark(string body) => body.Length > 0 && body[0] == '﻿' ? body[1..] : body;

    private static ScriptKind SyntaxKind(string syntax)
    {
        var value = syntax?.Trim();

        if (string.IsNullOrEmpty(value) || string.Equals(value, "PowerShell", StringComparison.OrdinalIgnoreCase)) return ScriptKind.PowerShell;

        return string.Equals(value, "Bash", StringComparison.OrdinalIgnoreCase) ? ScriptKind.Bash : ScriptKind.Other;
    }

    private enum ScriptKind { PowerShell, Bash, Other }

    private sealed record TemplateParameter(string Name, string Value, bool IsSensitive);

    private sealed record ParameterEntry(string Name, EntryValue Value);

    /// <summary>Either a readable literal known at import time, or decoder arguments resolved at deploy time.</summary>
    private sealed record EntryValue(bool IsLiteral, string Text)
    {
        public static EntryValue Literal(string text) => new(true, text);

        public static EntryValue Arguments(string arguments) => new(false, arguments);
    }

    private sealed class CompatibilityContext(OctopusDeploymentActionDto action, string syntax, string body, OctopusActionTemplateDto template)
    {
        // Source
        public OctopusDeploymentActionDto Action { get; } = action;
        public string Syntax { get; } = syntax;
        public ScriptKind Kind { get; } = SyntaxKind(syntax);
        public OctopusActionTemplateDto Template { get; } = template;
        public string Body { get; set; } = body;

        // Resolved Octopus inputs
        public List<TemplateParameter> Parameters { get; set; } = [];
        public Dictionary<string, TemplateParameter> Siblings { get; set; } = new(StringComparer.OrdinalIgnoreCase);
        public HashSet<string> SensitiveParameterNames { get; set; } = new(StringComparer.OrdinalIgnoreCase);
        public IReadOnlyList<string> References { get; set; } = [];
        public bool SubstitutionUnparsable { get; set; }

        // Output
        public List<ParameterEntry> Entries { get; } = [];
        public List<OctopusImportDiagnosticDto> Diagnostics { get; } = [];
        private HashSet<string> Reported { get; } = new(StringComparer.Ordinal);

        public void Report(OctopusImportCompatibilitySeverity severity, string code, string message)
        {
            if (!Reported.Add($"{code}\n{message}")) return;

            Diagnostics.Add(OctopusImportKubernetesActionMapperSupport.Diagnostic(severity, code, message, Action));
        }

        public OctopusScriptCompatibilityResult Result(string scriptBody) => new(scriptBody, Diagnostics);
    }
}

internal sealed record OctopusScriptCompatibilityResult(string ScriptBody, IReadOnlyList<OctopusImportDiagnosticDto> Diagnostics);
