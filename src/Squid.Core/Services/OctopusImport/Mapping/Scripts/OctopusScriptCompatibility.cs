using System.Text;
using System.Text.RegularExpressions;
using Squid.Core.Services.OctopusImport.Mapping.Actions;
using Squid.Core.Services.OctopusImport.Octopus;
using Squid.Message.Enums.OctopusImport;
using Squid.Message.Models.OctopusImport;

namespace Squid.Core.Services.OctopusImport.Mapping.Scripts;

/// <summary>
/// Makes an imported Octopus inline script run unchanged on Squid by prepending a small, clearly
/// delimited compatibility preamble:
/// <list type="bullet">
///   <item>Step-template parameter values (from the action, else the template default) become
///         <c>$OctopusParameters['Name']</c> entries and — for valid identifiers — <c>$Name</c>
///         PowerShell variables, matching what Octopus/Calamari exposes.</item>
///   <item>Every key the script reads through <c>$OctopusParameters['…']</c> (PowerShell) or
///         <c>get_octopusvariable "…"</c> (Bash) is defined: Octopus built-ins map to their Squid
///         equivalent, other names resolve to the Squid variable of the same name.</item>
/// </list>
/// Values are emitted as <c>#{…}</c> expressions inside quoted here-docs, so Squid's own variable
/// substitution fills them at deploy time and the shell never re-interprets them.
/// </summary>
internal static partial class OctopusScriptCompatibility
{
    public const string PreambleStartMarker = "# --- Squid: Octopus compatibility (generated by Octopus import) ---";
    public const string PreambleEndMarker = "# --- end Octopus compatibility ---";

    private const string BashHeredocDelimiter = "SQUID_OCTOPUS_VALUE";

    public static OctopusScriptCompatibilityResult Apply(OctopusDeploymentActionDto action, string syntax, string scriptBody, OctopusActionTemplateDto template)
    {
        var diagnostics = new List<OctopusImportDiagnosticDto>();
        var parameters = ResolveTemplateParameters(action, template, diagnostics);
        var references = ExtractReferencedKeys(syntax, scriptBody);

        if (parameters.Count == 0 && references.Count == 0) return new OctopusScriptCompatibilityResult(scriptBody, diagnostics);

        var entries = BuildEntries(action, parameters, references, diagnostics);
        var preamble = RenderPreamble(action, syntax, scriptBody, entries, parameters, diagnostics);

        if (preamble == null) return new OctopusScriptCompatibilityResult(scriptBody, diagnostics);

        diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Info, OctopusImportActionMappingDiagnosticCodes.ScriptOctopusCompatibilityAdded, $"Octopus script action '{action.Name}' received a compatibility preamble defining {entries.Count} Octopus parameter(s) for Squid.", action));

        return new OctopusScriptCompatibilityResult(preamble + scriptBody, diagnostics);
    }

    // ── Template parameters ───────────────────────────────────────────────────────────

    private static List<TemplateParameter> ResolveTemplateParameters(OctopusDeploymentActionDto action, OctopusActionTemplateDto template, List<OctopusImportDiagnosticDto> diagnostics)
    {
        var properties = action.Properties ?? [];
        var templateId = GetProperty(properties, OctopusPropertyNames.ActionTemplateId);

        if (string.IsNullOrWhiteSpace(templateId)) return [];

        if (template == null)
            diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Warning, OctopusImportActionMappingDiagnosticCodes.StepTemplateMissingFromExport, $"Octopus action '{action.Name}' uses step template '{templateId}', which is not in the export; parameter defaults are unknown, only values stored on the action were imported.", action));

        var definitions = (template?.Parameters ?? []).Where(p => !string.IsNullOrWhiteSpace(p.Name)).GroupBy(p => p.Name, StringComparer.OrdinalIgnoreCase).ToDictionary(g => g.Key, g => g.First(), StringComparer.OrdinalIgnoreCase);
        var names = definitions.Keys.Concat(properties.Keys.Where(IsTemplateParameterKey)).Distinct(StringComparer.OrdinalIgnoreCase);

        return names.Select(name => ResolveTemplateParameter(name, properties, definitions)).OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase).ToList();
    }

    private static TemplateParameter ResolveTemplateParameter(string name, Dictionary<string, string> properties, Dictionary<string, OctopusActionTemplateParameterDto> definitions)
    {
        definitions.TryGetValue(name, out var definition);

        var hasActionValue = TryGetPropertyRaw(properties, name, out var actionValue);
        var value = hasActionValue ? actionValue : definition?.PlainDefaultValue;
        var isSensitive = definition?.IsSensitive == true;

        return new TemplateParameter(definition?.Name ?? name, value, isSensitive);
    }

    // Octopus stores template parameter values on the action under their bare parameter name;
    // every Octopus-owned property is namespaced "Octopus.".
    private static bool IsTemplateParameterKey(string key) => !string.IsNullOrWhiteSpace(key) && !OctopusSystemVariables.IsOctopusName(key);

    // ── Referenced keys ───────────────────────────────────────────────────────────────

    private static IReadOnlyList<string> ExtractReferencedKeys(string syntax, string scriptBody)
    {
        if (string.IsNullOrEmpty(scriptBody)) return [];

        var pattern = SyntaxKind(syntax) switch
        {
            ScriptKind.PowerShell => PowerShellParameterReference(),
            ScriptKind.Bash => BashParameterReference(),
            _ => null
        };

        if (pattern == null) return [];

        return pattern.Matches(scriptBody).Select(m => m.Groups["key"].Value).Where(k => !string.IsNullOrWhiteSpace(k)).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
    }

    // ── Entries ───────────────────────────────────────────────────────────────────────

    private static List<ParameterEntry> BuildEntries(OctopusDeploymentActionDto action, List<TemplateParameter> parameters, IReadOnlyList<string> references, List<OctopusImportDiagnosticDto> diagnostics)
    {
        var entries = new List<ParameterEntry>();
        var parameterNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var parameter in parameters)
        {
            parameterNames.Add(parameter.Name);
            entries.Add(BuildParameterEntry(action, parameter, diagnostics));
        }

        foreach (var key in references.Where(k => !parameterNames.Contains(k)))
            entries.Add(BuildReferenceEntry(action, key, diagnostics));

        return entries;
    }

    private static ParameterEntry BuildParameterEntry(OctopusDeploymentActionDto action, TemplateParameter parameter, List<OctopusImportDiagnosticDto> diagnostics)
    {
        if (!parameter.IsSensitive) return new ParameterEntry(parameter.Name, ParameterValueKind.Literal, OctopusSystemVariables.RewriteReferences(parameter.Value ?? string.Empty));

        // Never write a secret into a script body: it would be stored and displayed in plain text.
        if (!string.IsNullOrEmpty(parameter.Value))
            diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Blocker, OctopusImportActionMappingDiagnosticCodes.SensitiveStepTemplateParameter, $"Octopus action '{action.Name}' sets sensitive step-template parameter '{parameter.Name}'. Sensitive template parameters cannot be inlined into a Squid script; create a sensitive project variable named '{parameter.Name}' and remove the value from the step before importing.", action));

        return new ParameterEntry(parameter.Name, ParameterValueKind.Expression, $"#{{{parameter.Name}}}");
    }

    private static ParameterEntry BuildReferenceEntry(OctopusDeploymentActionDto action, string key, List<OctopusImportDiagnosticDto> diagnostics)
    {
        if (!OctopusSystemVariables.IsOctopusName(key)) return new ParameterEntry(key, ParameterValueKind.Expression, $"#{{{key}}}");

        if (OctopusSystemVariables.TryGetSquidName(key, out var squidName)) return new ParameterEntry(key, ParameterValueKind.Expression, $"#{{{squidName}}}");

        diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Warning, OctopusImportActionMappingDiagnosticCodes.ScriptUnmappedOctopusVariable, $"Octopus script action '{action.Name}' reads '{key}', which has no Squid equivalent; it will be empty when the script runs on Squid.", action));

        return new ParameterEntry(key, ParameterValueKind.Literal, string.Empty);
    }

    // ── Rendering ─────────────────────────────────────────────────────────────────────

    private static string RenderPreamble(OctopusDeploymentActionDto action, string syntax, string scriptBody, List<ParameterEntry> entries, List<TemplateParameter> parameters, List<OctopusImportDiagnosticDto> diagnostics)
    {
        switch (SyntaxKind(syntax))
        {
            case ScriptKind.PowerShell when MustStayFirst(scriptBody):
                diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Warning, OctopusImportActionMappingDiagnosticCodes.ScriptOctopusCompatibilityUnavailable, $"Octopus script action '{action.Name}' starts with a param()/using block, so the Octopus compatibility preamble could not be prepended. Replace $OctopusParameters / template parameter references with #{{...}} expressions.", action));
                return null;
            case ScriptKind.PowerShell:
                return RenderPowerShell(entries, parameters);
            case ScriptKind.Bash:
                return RenderBash(entries);
            default:
                diagnostics.Add(Diagnostic(OctopusImportCompatibilitySeverity.Warning, OctopusImportActionMappingDiagnosticCodes.ScriptOctopusCompatibilityUnavailable, $"Octopus script action '{action.Name}' uses step-template parameters but its syntax '{syntax}' has no Octopus compatibility preamble. Replace parameter references with #{{...}} expressions.", action));
                return null;
        }
    }

    private static string RenderPowerShell(List<ParameterEntry> entries, List<TemplateParameter> parameters)
    {
        var sb = new StringBuilder();

        sb.Append(PreambleStartMarker).Append('\n');
        sb.Append("if ($null -eq $OctopusParameters) { $OctopusParameters = @{} }").Append('\n');

        foreach (var entry in entries)
            sb.Append("$OctopusParameters['").Append(EscapePowerShellSingleQuoted(entry.Name)).Append("'] = ").Append(PowerShellValue(entry)).Append('\n');

        foreach (var parameter in parameters.Where(p => PowerShellIdentifier().IsMatch(p.Name)))
            sb.Append('$').Append(parameter.Name).Append(" = $OctopusParameters['").Append(EscapePowerShellSingleQuoted(parameter.Name)).Append("']").Append('\n');

        sb.Append(PreambleEndMarker).Append('\n');

        return sb.ToString();
    }

    private static string PowerShellValue(ParameterEntry entry)
    {
        if (entry.Kind == ParameterValueKind.Literal && !entry.Value.Contains("#{", StringComparison.Ordinal)) return $"'{EscapePowerShellSingleQuoted(entry.Value)}'";

        // Expression (or a literal that itself contains #{...}): Squid substitutes the text before the
        // script runs, so the value lands inside a single-quoted here-string and is never re-parsed.
        return $"@'\n{entry.Value}\n'@";
    }

    private static string RenderBash(List<ParameterEntry> entries)
    {
        var sb = new StringBuilder();

        sb.Append(PreambleStartMarker).Append('\n');
        sb.Append("get_octopusvariable() {").Append('\n');
        sb.Append("  case \"$1\" in").Append('\n');

        foreach (var entry in entries)
            sb.Append("    '").Append(EscapeBashSingleQuoted(entry.Name)).Append("') ").Append(BashValue(entry)).Append(" ;;").Append('\n');

        sb.Append("    *) printf '' ;;").Append('\n');
        sb.Append("  esac").Append('\n');
        sb.Append('}').Append('\n');
        sb.Append(PreambleEndMarker).Append('\n');

        return sb.ToString();
    }

    private static string BashValue(ParameterEntry entry)
    {
        if (entry.Kind == ParameterValueKind.Literal && !entry.Value.Contains("#{", StringComparison.Ordinal)) return $"printf '%s' '{EscapeBashSingleQuoted(entry.Value)}'";

        return $"cat <<'{BashHeredocDelimiter}'\n{entry.Value}\n{BashHeredocDelimiter}\n   ";
    }

    // ── Helpers ───────────────────────────────────────────────────────────────────────

    private static bool MustStayFirst(string scriptBody) => LeadingParamOrUsingBlock().IsMatch(scriptBody ?? string.Empty);

    private static ScriptKind SyntaxKind(string syntax)
    {
        var value = syntax?.Trim();

        if (string.IsNullOrEmpty(value) || string.Equals(value, "PowerShell", StringComparison.OrdinalIgnoreCase)) return ScriptKind.PowerShell;

        return string.Equals(value, "Bash", StringComparison.OrdinalIgnoreCase) ? ScriptKind.Bash : ScriptKind.Other;
    }

    private static string EscapePowerShellSingleQuoted(string value) => (value ?? string.Empty).Replace("'", "''", StringComparison.Ordinal);

    private static string EscapeBashSingleQuoted(string value) => (value ?? string.Empty).Replace("'", "'\\''", StringComparison.Ordinal);

    private static string GetProperty(Dictionary<string, string> properties, string name) => TryGetPropertyRaw(properties, name, out var value) ? value : null;

    private static bool TryGetPropertyRaw(Dictionary<string, string> properties, string name, out string value)
    {
        var match = properties.FirstOrDefault(p => string.Equals(p.Key, name, StringComparison.OrdinalIgnoreCase));

        value = match.Value;

        return match.Key != null;
    }

    private static OctopusImportDiagnosticDto Diagnostic(OctopusImportCompatibilitySeverity severity, string code, string message, OctopusDeploymentActionDto action)
        => OctopusImportKubernetesActionMapperSupport.Diagnostic(severity, code, message, action);

    [GeneratedRegex(@"\$OctopusParameters\[\s*(?<q>['""])(?<key>[^'""\r\n]+)\k<q>\s*\]", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase)]
    private static partial Regex PowerShellParameterReference();

    [GeneratedRegex(@"get_octopusvariable\s+(?:(?<q>['""])(?<key>[^'""\r\n]+)\k<q>|(?<key>[^\s'""`$()]+))", RegexOptions.CultureInvariant)]
    private static partial Regex BashParameterReference();

    [GeneratedRegex(@"^[A-Za-z_][A-Za-z0-9_]*$", RegexOptions.CultureInvariant)]
    private static partial Regex PowerShellIdentifier();

    [GeneratedRegex(@"\A(?:\s|#[^\r\n]*(?:\r?\n|\z)|<#[\s\S]*?#>)*(?:param\s*\(|using\s+(?:namespace|module|assembly)\b)", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase)]
    private static partial Regex LeadingParamOrUsingBlock();

    private enum ScriptKind { PowerShell, Bash, Other }

    private enum ParameterValueKind { Literal, Expression }

    private sealed record TemplateParameter(string Name, string Value, bool IsSensitive);

    private sealed record ParameterEntry(string Name, ParameterValueKind Kind, string Value);
}

internal sealed record OctopusScriptCompatibilityResult(string ScriptBody, IReadOnlyList<OctopusImportDiagnosticDto> Diagnostics);
