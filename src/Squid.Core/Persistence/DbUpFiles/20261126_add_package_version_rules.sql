-- How a package gets its version when it is uploaded to a feed: one version template per (feed, package), e.g. "1.0.{counter}" or "{date:yyyy.MM.dd}.{counter:daily}".
-- A package without a row uses the built-in default template, so the table holds only the packages somebody configured.
-- package_version_counter backs the {counter} token: one row per (feed, package, scope), where scope is the text rendered before the token (plus the UTC date for
-- {counter:daily}). The server takes numbers with a single INSERT ... ON CONFLICT DO UPDATE ... RETURNING, so concurrent uploads never get the same number.
-- Rows go when their feed goes. Additive and re-runnable.
CREATE TABLE IF NOT EXISTS package_version_rule
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id integer NOT NULL REFERENCES external_feed (id) ON DELETE CASCADE,
    package_id character varying(255) NOT NULL,
    version_template character varying(256) NOT NULL,
    created_date timestamp with time zone NOT NULL DEFAULT now(),
    created_by integer NOT NULL DEFAULT 8888,
    last_modified_date timestamp with time zone NOT NULL DEFAULT now(),
    last_modified_by integer NOT NULL DEFAULT 8888,
    CONSTRAINT uq_package_version_rule_feed_package UNIQUE (feed_id, package_id)
);

CREATE TABLE IF NOT EXISTS package_version_counter
(
    feed_id integer NOT NULL REFERENCES external_feed (id) ON DELETE CASCADE,
    package_id character varying(255) NOT NULL,
    scope text NOT NULL,
    value bigint NOT NULL,
    last_modified_date timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (feed_id, package_id, scope)
);
