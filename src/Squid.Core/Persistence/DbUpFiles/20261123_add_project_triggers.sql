CREATE TABLE project_trigger
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id integer NOT NULL,
    project_id integer NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    name varchar(200) NOT NULL,
    description text,
    trigger_type varchar(64) NOT NULL,
    action_type varchar(64) NOT NULL,
    configuration_json jsonb NOT NULL,
    is_disabled boolean NOT NULL,
    is_deleted boolean NOT NULL DEFAULT false,
    revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
    execution_revision integer NOT NULL DEFAULT 1 CHECK (execution_revision BETWEEN 1 AND revision),
    execution_user_id integer NOT NULL,
    created_date timestamptz NOT NULL,
    created_by integer NOT NULL,
    last_modified_date timestamptz NOT NULL,
    last_modified_by integer NOT NULL
);

CREATE INDEX ix_project_trigger_project ON project_trigger (project_id, is_deleted, id);

CREATE TABLE project_trigger_state
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_id integer NOT NULL REFERENCES project_trigger(id) ON DELETE CASCADE,
    source_key varchar(512) NOT NULL,
    cursor text,
    last_checked_at timestamptz,
    last_outcome text,
    next_due_at timestamptz
);

CREATE UNIQUE INDEX ux_project_trigger_state_source ON project_trigger_state (trigger_id, source_key);
CREATE INDEX ix_project_trigger_state_due ON project_trigger_state (next_due_at) WHERE next_due_at IS NOT NULL;

CREATE TABLE project_trigger_run
(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_id integer NOT NULL REFERENCES project_trigger(id) ON DELETE CASCADE,
    revision integer NOT NULL,
    execution_user_id integer NOT NULL,
    trigger_type varchar(64) NOT NULL,
    action_type varchar(64) NOT NULL,
    configuration_json jsonb NOT NULL,
    source_key varchar(512) NOT NULL,
    occurrence_key varchar(512) NOT NULL,
    evidence_json jsonb NOT NULL,
    action_plan_json jsonb,
    observed_at timestamptz NOT NULL,
    status varchar(32) NOT NULL,
    reason text,
    attempts integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL,
    completed_at timestamptz,
    release_id integer,
    deployment_id integer,
    task_id integer
);

CREATE UNIQUE INDEX ux_project_trigger_run_occurrence ON project_trigger_run (trigger_id, occurrence_key);
CREATE INDEX ix_project_trigger_run_history ON project_trigger_run (trigger_id, observed_at, id);
CREATE INDEX ix_project_trigger_run_due ON project_trigger_run (status, next_attempt_at, id);
CREATE INDEX ix_project_trigger_run_deployment ON project_trigger_run (deployment_id) WHERE deployment_id IS NOT NULL;
