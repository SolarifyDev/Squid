-- The built-in package feed: packages pushed to Squid itself instead of an external feed. One feed of type 'BuiltIn' per space, and every pushed
-- version is one row of builtin_package that points at its file (store_id + blob_key) in a package store. Nothing reads or writes these tables until
-- somebody pushes a package, so this changes no existing behaviour. Additive and re-runnable.

-- At most one built-in feed per space: the data seeder and the space-creation path insert with ON CONFLICT DO NOTHING against this index, so two
-- replicas starting together cannot both create one.
CREATE UNIQUE INDEX IF NOT EXISTS ux_external_feed_builtin_per_space ON external_feed (space_id) WHERE feed_type = 'BuiltIn';

CREATE TABLE IF NOT EXISTS builtin_package
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id integer NOT NULL,
    feed_id integer NOT NULL REFERENCES external_feed (id) ON DELETE CASCADE,
    package_id character varying(255) NOT NULL,
    version character varying(255) NOT NULL,
    file_extension character varying(16) NOT NULL,
    size_bytes bigint NOT NULL,
    sha256 character varying(64) NOT NULL,
    -- A package store cannot be deleted while a row still points at it.
    store_id integer NOT NULL REFERENCES package_store (id),
    blob_key character varying(512) NOT NULL,
    published_date timestamp with time zone NOT NULL DEFAULT now(),
    published_by integer NOT NULL DEFAULT 8888,
    source character varying(16) NOT NULL
);

-- Package ids are case-insensitive: one version exists once per feed whatever the casing it was pushed with.
CREATE UNIQUE INDEX IF NOT EXISTS ux_builtin_package_feed_package_version ON builtin_package (feed_id, lower(package_id), version);

CREATE INDEX IF NOT EXISTS ix_builtin_package_store ON builtin_package (store_id);

-- The canonical casing of each package id: the first push of a package fixes it, so later pushes with another casing reuse it and the version rules and
-- counters, which key on the exact id string, stay consistent. A separate row, taken with INSERT ... ON CONFLICT DO NOTHING, decides it atomically
-- even when two first pushes race.
CREATE TABLE IF NOT EXISTS builtin_package_name
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id integer NOT NULL REFERENCES external_feed (id) ON DELETE CASCADE,
    package_id character varying(255) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_builtin_package_name_feed_package ON builtin_package_name (feed_id, lower(package_id));
