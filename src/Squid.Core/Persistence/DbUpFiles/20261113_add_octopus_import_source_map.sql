-- Persistent Octopus source id -> Squid id provenance. Single idempotency key for re-import,
-- retention exemption and imported-history read-only guard. Additive; non-breaking.
CREATE TABLE IF NOT EXISTS octopus_import_source_map (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id integer NOT NULL,
    source_type varchar(64) NOT NULL,
    source_id varchar(200) NOT NULL,
    destination_id integer NOT NULL,
    outcome_state varchar(16) NOT NULL,
    fingerprint varchar(64) NULL,
    detail_fingerprint varchar(64) NULL,
    last_session_id uuid NULL,
    created_date timestamptz NOT NULL DEFAULT now(),
    created_by integer NOT NULL DEFAULT 8888,
    last_modified_date timestamptz NOT NULL DEFAULT now(),
    last_modified_by integer NOT NULL DEFAULT 8888
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_octopus_import_source_map_key
    ON octopus_import_source_map (space_id, source_type, source_id);

CREATE INDEX IF NOT EXISTS ix_octopus_import_source_map_destination
    ON octopus_import_source_map (source_type, destination_id);

ALTER TABLE release
    ADD COLUMN IF NOT EXISTS release_notes text NULL;

-- Backfill from imports that already succeeded, so a re-import recognises them. The newest succeeded
-- session wins per (space, type, id). Fingerprints stay NULL: the next re-import treats history as
-- changed once and normalises it. Source names are not copied (the stored value can be redacted).
-- Re-runnable: ON CONFLICT DO NOTHING never overwrites a row a later confirmation wrote.
INSERT INTO octopus_import_source_map (space_id, source_type, source_id, destination_id, outcome_state, last_session_id, created_date, last_modified_date)
SELECT space_id, source_type, source_id, destination_id, outcome_state, session_id, completed_at, completed_at
FROM (
    SELECT DISTINCT ON (s.destination_space_id, m->>'sourceType', upper(trim(m->>'sourceId')))
        s.destination_space_id AS space_id,
        m->>'sourceType' AS source_type,
        upper(trim(m->>'sourceId')) AS source_id,
        (m->>'destinationId')::integer AS destination_id,
        m->>'outcomeState' AS outcome_state,
        s.session_id AS session_id,
        COALESCE(s.completed_at, s.last_modified_date) AS completed_at
    FROM octopus_import_session s
    CROSS JOIN LATERAL jsonb_array_elements(
        CASE WHEN jsonb_typeof(s.result_json->'idMappings') = 'array' THEN s.result_json->'idMappings' ELSE '[]'::jsonb END) AS m
    WHERE s.state = 'Succeeded'
      AND COALESCE(trim(m->>'sourceType'), '') <> ''
      AND COALESCE(trim(m->>'sourceId'), '') <> ''
      AND CASE WHEN (m->>'destinationId') ~ '^[1-9][0-9]{0,9}$' THEN (m->>'destinationId')::bigint END BETWEEN 1 AND 2147483647
      AND m->>'outcomeState' IN ('Created', 'Reused')
    ORDER BY s.destination_space_id, m->>'sourceType', upper(trim(m->>'sourceId')), s.completed_at DESC NULLS LAST, s.id DESC
) AS latest
WHERE length(source_type) <= 64 AND length(source_id) <= 200
ON CONFLICT (space_id, source_type, source_id) DO NOTHING;
