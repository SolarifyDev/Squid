-- Runbook foundation: an independently owned draft process, a reserved
-- variable set, and explicit ownership metadata on shared process rows.
--
-- Process kinds are pinned by the application enum:
--   ProjectDeployment = 0
--   Runbook           = 1
--
-- `deployment_process.owner_id` deliberately has no FK to `runbook.id`:
-- `runbook.process_id` already references the process, and a reverse FK would
-- make the aggregate cyclic. The check constraint, one-process-per-runbook
-- unique index, and service ownership checks enforce the two-sided invariant.

ALTER TABLE deployment_process
    ADD COLUMN IF NOT EXISTS process_kind integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS owner_id integer NULL;

-- Keep NULL as the database default. EF's optional int mapping also needs the
-- column to be nullable for the ownership check to represent project processes.
ALTER TABLE deployment_process
    ALTER COLUMN owner_id DROP NOT NULL,
    ALTER COLUMN owner_id DROP DEFAULT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'CheckRunbookOwnership'
          AND conrelid = 'deployment_process'::regclass
    ) THEN
        ALTER TABLE deployment_process
            ADD CONSTRAINT "CheckRunbookOwnership"
            CHECK (
                (process_kind = 0 AND owner_id IS NULL)
                OR
                (process_kind = 1 AND owner_id IS NOT NULL AND owner_id > 0)
            );
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_deployment_process_runbook_owner
    ON deployment_process (owner_id)
    WHERE process_kind = 1;

CREATE TABLE IF NOT EXISTS runbook
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id integer NOT NULL,
    space_id integer NOT NULL,
    name character varying(200) NOT NULL,
    description text NULL,
    tags_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    process_id integer NOT NULL,
    variable_set_id integer NOT NULL,
    created_date timestamp with time zone NOT NULL DEFAULT now(),
    created_by integer NOT NULL DEFAULT 8888,
    last_modified_date timestamp with time zone NOT NULL DEFAULT now(),
    last_modified_by integer NOT NULL DEFAULT 8888
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_runbook_process_id
    ON runbook (process_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_runbook_variable_set_id
    ON runbook (variable_set_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_runbook_project_normalized_name
    ON runbook (project_id, lower(btrim(name)));

CREATE INDEX IF NOT EXISTS ix_runbook_project
    ON runbook (project_id);

CREATE INDEX IF NOT EXISTS ix_runbook_space_project
    ON runbook (space_id, project_id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_variable_set_runbook_owner
    ON variable_set (owner_id)
    WHERE owner_type = 4;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_runbook_process_id'
          AND conrelid = 'runbook'::regclass
    ) THEN
        ALTER TABLE runbook
            ADD CONSTRAINT fk_runbook_process_id
            FOREIGN KEY (process_id)
            REFERENCES deployment_process (id)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_runbook_variable_set_id'
          AND conrelid = 'runbook'::regclass
    ) THEN
        ALTER TABLE runbook
            ADD CONSTRAINT fk_runbook_variable_set_id
            FOREIGN KEY (variable_set_id)
            REFERENCES variable_set (id)
            ON DELETE RESTRICT;
    END IF;
END $$;
