CREATE TABLE runbook_snapshot
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runbook_id integer NOT NULL,
    version integer NOT NULL CHECK (version > 0),
    published_at timestamptz NOT NULL,
    published_by integer NOT NULL,
    snapshot_data bytea NOT NULL,
    content_hash varchar(64) NOT NULL,
    compression_type varchar(16) NOT NULL DEFAULT 'GZIP',
    uncompressed_size integer NOT NULL,
    CONSTRAINT uq_runbook_snapshot_owner UNIQUE (runbook_id, id),
    CONSTRAINT uq_runbook_snapshot_version UNIQUE (runbook_id, version),
    CONSTRAINT fk_runbook_snapshot_runbook FOREIGN KEY (runbook_id)
        REFERENCES runbook (id) ON DELETE RESTRICT
);

ALTER TABLE runbook ADD COLUMN published_snapshot_id integer NULL;

ALTER TABLE runbook ADD CONSTRAINT fk_runbook_published_snapshot
    FOREIGN KEY (id, published_snapshot_id)
    REFERENCES runbook_snapshot (runbook_id, id) ON DELETE RESTRICT;

CREATE FUNCTION prevent_runbook_snapshot_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Runbook snapshots are immutable.' USING ERRCODE = '55000';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_runbook_snapshot_immutable
    BEFORE UPDATE OR DELETE ON runbook_snapshot
    FOR EACH ROW EXECUTE FUNCTION prevent_runbook_snapshot_mutation();
