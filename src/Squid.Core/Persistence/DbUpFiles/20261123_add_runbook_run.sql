CREATE TABLE runbook_run
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runbook_id integer NOT NULL,
    snapshot_id integer NOT NULL,
    server_task_id integer NOT NULL,
    project_id integer NOT NULL,
    space_id integer NOT NULL,
    environment_id integer NOT NULL,
    initiated_by integer NOT NULL,
    created_date timestamptz NOT NULL DEFAULT now(),
    created_by integer NOT NULL DEFAULT 8888,
    last_modified_date timestamptz NOT NULL DEFAULT now(),
    last_modified_by integer NOT NULL DEFAULT 8888,
    CONSTRAINT uq_runbook_run_server_task UNIQUE (server_task_id),
    CONSTRAINT fk_runbook_run_runbook FOREIGN KEY (runbook_id)
        REFERENCES runbook (id) ON DELETE RESTRICT,
    CONSTRAINT fk_runbook_run_snapshot FOREIGN KEY (runbook_id, snapshot_id)
        REFERENCES runbook_snapshot (runbook_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_runbook_run_server_task FOREIGN KEY (server_task_id)
        REFERENCES server_task (id) ON DELETE RESTRICT
);

CREATE INDEX ix_runbook_run_runbook_created
    ON runbook_run (runbook_id, created_date);
