-- Where uploaded packages are kept (the future built-in feed stores through this). System-wide, so no space_id. Editable through the API; the
-- row seeded below keeps a plain install working with no setup. Nothing reads or writes packages yet, so this changes no existing behaviour.
-- properties holds the non-secret settings of the store kind as JSON; secret holds its secret settings, encrypted at rest by the application.
-- Additive and re-runnable.
CREATE TABLE IF NOT EXISTS package_store
(
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    kind varchar(64) NOT NULL,
    properties text NOT NULL DEFAULT '{}',
    secret text NULL,
    is_default boolean NOT NULL DEFAULT false,
    created_date timestamptz NOT NULL DEFAULT now(),
    created_by integer NOT NULL DEFAULT 8888,
    last_modified_date timestamptz NOT NULL DEFAULT now(),
    last_modified_by integer NOT NULL DEFAULT 8888,
    last_tested_date timestamptz NULL,
    last_test_succeeded boolean NULL,
    last_test_message text NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_package_store_name ON package_store (name);

-- At most one default store: a second row with is_default = true is refused by the database.
CREATE UNIQUE INDEX IF NOT EXISTS ux_package_store_single_default ON package_store (is_default) WHERE is_default;

-- The default store is a folder on local disk. An empty root means "decide at runtime" (under the data directory when one is configured).
-- Only when the table is empty, so a store the operator has already created or renamed is never joined by a second default.
INSERT INTO package_store (name, kind, properties, is_default)
SELECT 'Local disk', 'FileSystem', '{}', true
WHERE NOT EXISTS (SELECT 1 FROM package_store);
